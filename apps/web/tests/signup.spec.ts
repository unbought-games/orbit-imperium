import {test,expect} from '@playwright/test';

test('new player signs up, builds, refreshes and signs back in on mobile',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/');
 await page.getByRole('link',{name:'Create an account',exact:true}).click();
 await expect(page.getByRole('button',{name:'Create account',exact:true})).toBeVisible();
 await page.screenshot({path:'target/signup-form-mobile.png',fullPage:true});
 await page.getByLabel('Account',{exact:true}).fill('  NewPlayer  ');
 await page.getByLabel('Password',{exact:true}).fill('simple-password');
 await page.route('**/api/v1/registration?bootstrap=true',async route=>{const response=await route.fetch();const payload=await response.json();expect(response.status()).toBe(201);expect(payload.result.game.status).toBe('ready');payload.result.game={status:'unavailable',code:'Unavailable'};await route.fulfill({response,json:payload})});
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await expect(page.getByRole('button',{name:'Retry connection'})).toBeVisible();
 await expect(page.getByLabel('Password')).toHaveCount(0);
 expect((await page.request.get('/api/v1/session')).status()).toBe(200);
 await page.unroute('**/api/v1/registration?bootstrap=true');
 await page.getByRole('button',{name:'Retry connection'}).click();
 await expect(page.getByRole('heading',{name:/^Overview —/,exact:true})).toBeVisible();
 const session=await(await page.request.get('/api/v1/session')).json();
 expect(session.memberships).toHaveLength(1);
 await page.getByRole('button',{name:'Menu',exact:true}).last().click();
 await page.getByRole('dialog').getByRole('link',{name:'Resources',exact:false}).click();
 await expect(async()=>{
  await page.getByRole('button',{name:'Upgrade Metal Mine',exact:true}).click();
  await expect(page.getByRole('button',{name:'Confirm upgrade',exact:true})).toBeVisible({timeout:1000});
 }).toPass({timeout:10000});
 await page.getByRole('button',{name:'Confirm upgrade',exact:true}).click();
 await expect(page.getByRole('button',{name:'Upgrade Metal Mine',exact:true}).getByLabel('Construction progress')).toBeVisible();
 const startupReads:string[]=[];
 page.on('request',r=>{const p=new URL(r.url()).pathname;if(p==='/api/v1/bootstrap'||p==='/api/v1/session'||p==='/api/v1/registration'||p.endsWith('/binding')||p.endsWith('/settings'))startupReads.push(p)});
 await page.reload();
 await expect(page.getByRole('button',{name:'Upgrade Metal Mine',exact:true}).getByLabel('Construction progress')).toBeVisible();
 expect(startupReads).toEqual([]);
 await page.getByRole('button',{name:'Menu',exact:true}).click();
 await page.getByRole('dialog',{name:'Navigation'}).getByRole('button',{name:'Sign out',exact:true}).click();
 await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Create an account',exact:true}).click();
 await expect(page.getByRole('button',{name:'Create account',exact:true})).toBeVisible();
 await page.getByLabel('Account',{exact:true}).fill('newplayer');
 await page.getByLabel('Password',{exact:true}).fill('different');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('already taken');
 await page.getByRole('link',{name:'Back to sign in',exact:true}).click();
 await expect(page.getByRole('button',{name:'Sign in',exact:true})).toBeVisible();
 await page.getByLabel('Account',{exact:true}).fill('NEWPLAYER');
 await page.getByLabel('Password',{exact:true}).fill('simple-password');
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('heading',{name:/^Overview —/,exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Menu',exact:true})).toBeVisible();
 expect((await(await page.request.get('/api/v1/session')).json()).account).toBe(session.account);
 await page.screenshot({path:'target/signup-mobile.png',fullPage:true});
});
