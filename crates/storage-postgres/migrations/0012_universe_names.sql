CREATE UNIQUE INDEX universe_names_unique ON universes (universe_name_key(name));

-- Serialize automatic selection with all name writes, including operator edits.
CREATE FUNCTION assign_universe_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(901330);
    IF NEW.name IS NULL THEN
        SELECT candidate INTO NEW.name
        FROM unnest(universe_default_names()) WITH ORDINALITY AS names(candidate, position)
        WHERE NOT EXISTS (SELECT 1 FROM universes WHERE universe_name_key(name) = universe_name_key(candidate))
        ORDER BY position LIMIT 1;
        IF NEW.name IS NULL THEN
            RAISE EXCEPTION 'No unused automatic galaxy names remain' USING ERRCODE = 'PON01';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER universe_name_assignment BEFORE INSERT OR UPDATE OF name ON universes
FOR EACH ROW EXECUTE FUNCTION assign_universe_name();

-- Stable ordering makes retained-world assignment reproducible.
DO $$ DECLARE universe_id uuid; BEGIN
    FOR universe_id IN SELECT id FROM universes ORDER BY id LOOP
        UPDATE universes SET name = NULL WHERE id = universe_id;
    END LOOP;
END $$;
ALTER TABLE universes ALTER COLUMN name SET NOT NULL;
ALTER TABLE universes ADD CONSTRAINT universe_name_valid CHECK (
    char_length(name) BETWEEN 1 AND 80 AND name = btrim(name)
    AND name !~ '[[:cntrl:]]'
);
