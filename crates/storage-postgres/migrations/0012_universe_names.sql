-- Names are authoritative; the URL key is computed, never stored as a column.
-- Automatic pool: common names plus 500 NGC galaxies (Type G) from OpenNGC.
-- Source: https://github.com/mattiaverga/OpenNGC/blob/master/database_files/NGC.csv
-- OpenNGC contributors, CC BY-SA 4.0; retrieved 2026-10-21.
CREATE FUNCTION universe_name_key(value text) RETURNS text
LANGUAGE plpgsql IMMUTABLE STRICT PARALLEL SAFE AS $$
DECLARE result text := ''; ch text;
BEGIN
    FOREACH ch IN ARRAY regexp_split_to_array(value, '') LOOP
        IF ch = ' ' THEN result := result || '-';
        ELSIF ch ~ '^[A-Za-z0-9-]$' THEN
            result := result || translate(ch, 'ABCDEFGHIJKLMNOPQRSTUVWXYZ', 'abcdefghijklmnopqrstuvwxyz');
        ELSE result := result || '~' || to_hex(ascii(ch)) || '~';
        END IF;
    END LOOP;
    RETURN result;
END $$;

